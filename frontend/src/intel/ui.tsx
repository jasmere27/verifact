import { useEffect, useRef } from "react";
import type { ReactNode } from "react";
import { ASSESSMENT_LABEL, PRIORITY_TONE, humanize } from "./lib";
import type { Loaded, Tone } from "./lib";
import type { Assessment, Health, IncidentStatus, Priority, RunStatus } from "./types";

/* ---------------------------------------------------------------- badges */

export function Badge({ tone = "neutral", children, plain }: { tone?: Tone; children: ReactNode; plain?: boolean }) {
  return <span className={`i-badge${tone === "neutral" ? "" : ` i-badge--${tone}`}${plain ? " i-badge--plain" : ""}`}>{children}</span>;
}

export function PriorityBadge({ p }: { p: Priority }) {
  return <Badge tone={PRIORITY_TONE[p]}>{humanize(p)}</Badge>;
}

const STATUS_TONE: Record<IncidentStatus, Tone> = {
  NEW: "accent",
  NEEDS_REVIEW: "warn",
  INVESTIGATING: "info",
  AWAITING_EVIDENCE: "warn",
  RESPONSE_DRAFTED: "info",
  RESOLVED: "ok",
  MONITORING: "neutral",
};

export function IncidentStatusBadge({ s }: { s: IncidentStatus }) {
  return <Badge tone={STATUS_TONE[s]}>{humanize(s)}</Badge>;
}

const ASSESSMENT_TONE: Record<Assessment, Tone> = {
  SUPPORTED: "ok",
  CONTRADICTED: "bad",
  MIXED: "warn",
  INSUFFICIENT_EVIDENCE: "neutral",
  MISSING_CONTEXT: "warn",
  UNDER_INVESTIGATION: "info",
};

export function AssessmentBadge({ a, short }: { a: Assessment; short?: boolean }) {
  const label = short ? ASSESSMENT_LABEL[a].replace(" by available evidence", "") : ASSESSMENT_LABEL[a];
  return <Badge tone={ASSESSMENT_TONE[a]}>{label}</Badge>;
}

const HEALTH: Record<Health, [Tone, string]> = {
  HEALTHY: ["ok", "Healthy"],
  DEGRADED: ["warn", "Degraded"],
  FAILING: ["bad", "Failing"],
  NEVER_RUN: ["neutral", "Not run yet"],
  PAUSED: ["neutral", "Paused"],
};

export function HealthBadge({ h }: { h: Health }) {
  return <Badge tone={HEALTH[h][0]}>{HEALTH[h][1]}</Badge>;
}

const RUN: Record<RunStatus, Tone> = { RUNNING: "info", SUCCEEDED: "ok", PARTIAL: "warn", FAILED: "bad", SKIPPED: "neutral" };

export function RunBadge({ s }: { s: RunStatus }) {
  return (
    <Badge tone={RUN[s]}>
      {s === "RUNNING" && <span className="i-spinner" aria-hidden="true" />}
      {humanize(s)}
    </Badge>
  );
}

/** Marks text produced by a model, so it is never mistaken for a verified fact. */
export function AiLabel({ what = "AI" }: { what?: string }) {
  return (
    <span className="i-ai" title="Generated by an AI model: review before relying on it.">
      {what}
    </span>
  );
}

/* ---------------------------------------------------------------- layout pieces */

export function PageHead({ title, sub, crumbs, actions }: { title: ReactNode; sub?: ReactNode; crumbs?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="i-page-head">
      <div>
        {crumbs && <div className="i-crumbs">{crumbs}</div>}
        <h1>{title}</h1>
        {sub && <p>{sub}</p>}
      </div>
      {actions && <div className="i-actions">{actions}</div>}
    </div>
  );
}

export function Panel({ title, actions, children, tight, id }: { title?: ReactNode; actions?: ReactNode; children: ReactNode; tight?: boolean; id?: string }) {
  return (
    <section className="i-panel" aria-labelledby={title && id ? id : undefined}>
      {(title || actions) && (
        <div className="i-panel-head">
          {title && <h2 id={id}>{title}</h2>}
          {actions && <div className="i-actions">{actions}</div>}
        </div>
      )}
      <div className={`i-panel-body${tight ? " tight" : ""}`}>{children}</div>
    </section>
  );
}

export function Empty({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="i-empty">
      <h2>{title}</h2>
      {children && <p>{children}</p>}
      {action}
    </div>
  );
}

export function Skeleton({ lines = 4 }: { lines?: number }) {
  return (
    <div className="i-skeleton" aria-busy="true" aria-label="Loading">
      {Array.from({ length: lines }, (_, i) => (
        <span key={i} style={{ width: `${90 - ((i * 17) % 40)}%` }} />
      ))}
    </div>
  );
}

export function ErrorBox({ error, onRetry }: { error: string; onRetry?: () => void }) {
  return (
    <div className="i-alert i-alert--bad" role="alert">
      <strong>Couldn't load this</strong>
      <span>{error}</span>
      {onRetry && (
        <span>
          <button type="button" className="i-btn i-btn--sm" onClick={onRetry}>
            Try again
          </button>
        </span>
      )}
    </div>
  );
}

export function Notice({ tone = "info", title, children }: { tone?: "info" | "warn" | "bad" | "ok"; title?: string; children: ReactNode }) {
  return (
    <div className={`i-alert i-alert--${tone}`} role={tone === "bad" ? "alert" : "status"}>
      {title && <strong>{title}</strong>}
      <span>{children}</span>
    </div>
  );
}

/** Wraps a loaded resource's three states. */
export function Load<T>({ r, children, lines }: { r: Loaded<T>; children: (data: T) => ReactNode; lines?: number }) {
  if (r.data) return <>{children(r.data)}</>;
  if (r.error) return <ErrorBox error={r.error} onRetry={r.reload} />;
  return <Skeleton lines={lines} />;
}

export function Pager({ page, size, total, onPage }: { page: number; size: number; total: number; onPage: (p: number) => void }) {
  const pages = Math.max(1, Math.ceil(total / size));
  if (total <= size) return null;
  return (
    <nav className="i-pager" aria-label="Pages">
      <span className="num">
        {page * size + 1}–{Math.min(total, (page + 1) * size)} of {total}
      </span>
      <span className="i-actions">
        <button type="button" className="i-btn i-btn--sm" disabled={page === 0} onClick={() => onPage(page - 1)}>
          Previous
        </button>
        <button type="button" className="i-btn i-btn--sm" disabled={page + 1 >= pages} onClick={() => onPage(page + 1)}>
          Next
        </button>
      </span>
    </nav>
  );
}

export function Dialog({ open, title, onClose, children, footer }: { open: boolean; title: string; onClose: () => void; children: ReactNode; footer?: ReactNode }) {
  const ref = useRef<HTMLDialogElement>(null);
  useEffect(() => {
    const d = ref.current;
    if (!d) return;
    if (open && !d.open) d.showModal();
    if (!open && d.open) d.close();
  }, [open]);
  return (
    <dialog ref={ref} className="i-dialog" onClose={onClose} aria-labelledby="i-dialog-title">
      {open && (
        <>
          <div className="i-dialog-head">
            <h2 id="i-dialog-title">{title}</h2>
            <button type="button" className="i-btn i-btn--ghost i-btn--sm" onClick={onClose} aria-label="Close">
              ✕
            </button>
          </div>
          <div className="i-dialog-body">{children}</div>
          {footer && <div className="i-dialog-foot">{footer}</div>}
        </>
      )}
    </dialog>
  );
}


/** {@code quota}: colours warn near and at the limit (usage); otherwise a plain bar (e.g. score factors). */
export function Meter({ value, max, label, quota = true }: { value: number; max: number; label: string; quota?: boolean }) {
  const pct = max <= 0 ? 0 : Math.min(100, Math.round((value / max) * 100));
  const tone = !quota ? " i-meter--plain" : pct >= 100 ? " i-meter--bad" : pct >= 80 ? " i-meter--warn" : "";
  return (
    <div className={`i-meter${tone}`} role="meter" aria-valuemin={0} aria-valuemax={max} aria-valuenow={value} aria-label={label}>
      <span style={{ width: `${pct}%` }} />
    </div>
  );
}

export function ExternalLink({ href, children }: { href: string; children: ReactNode }) {
  return (
    <a href={href} target="_blank" rel="noopener noreferrer nofollow">
      {children}
    </a>
  );
}

